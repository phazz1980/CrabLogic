/// The Latin character that an HD44780 ROM shows in place of a look-alike Cyrillic letter.
pub fn latin_twin(c: u16) -> Option<u8> {
    Some(match c {
        0x410 => b'A',
        0x412 => b'B',
        0x415 => b'E',
        0x41A => b'K',
        0x41C => b'M',
        0x41D => b'H',
        0x41E => b'O',
        0x420 => b'P',
        0x421 => b'C',
        0x422 => b'T',
        0x425 => b'X',
        0x430 => b'a',
        0x435 => b'e',
        0x43E => b'o',
        0x440 => b'p',
        0x441 => b'c',
        0x443 => b'y',
        0x445 => b'x',
        _ => return None,
    })
}

/// True when the font has a glyph for `c` (otherwise [`glyph`] gives `?`).
pub fn known(c: u16) -> bool {
    matches!(c, 0x20..=0x7E | 0xB0 | 0x401 | 0x451 | 0x410..=0x44F)
        || (ICON_BASE..ICON_BASE + ICONS as u16).contains(&c)
}

/// Glyph rows of `c` (codes below 0x20 are blanks, unknown characters are `?`).
pub fn glyph(c: u16) -> [u8; 8] {
    match c {
        0..=0x1F => ASCII[0],
        0x20..=0x7E => ASCII.rd((c - 0x20) as usize),
        0xB0 => DEGREE,
        0x401 => YO_UP,
        0x451 => YO_LOW,
        0x410..=0x42F => CYR_UP.rd((c - 0x410) as usize),
        0x430..=0x44F => CYR_LOW.rd((c - 0x430) as usize),
        _ if (ICON_BASE..ICON_BASE + ICONS as u16).contains(&c) => {
            ICON_ART.rd((c - ICON_BASE) as usize)
        }
        _ => ASCII[(b'?' - 0x20) as usize],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_rows_use_five_bits() {
        for c in 0..0xF000u16 {
            for r in glyph(c) {
                assert!(r < 32);
            }
        }
    }

    #[test]
    fn twins_share_glyph_with_latin() {
        for c in 0x400..0x460u16 {
            if let Some(l) = latin_twin(c) {
                assert_eq!(glyph(c), glyph(l as u16), "{c:#x}");
            }
        }
    }

    #[test]
    fn every_cyrillic_letter_is_known_and_nonblank() {
        for c in (0x410..=0x44Fu16).chain([0x401, 0x451]) {
            assert!(known(c));
            assert!(glyph(c).iter().any(|&r| r != 0), "{c:#x}");
        }
    }

    #[test]
    fn distinct_cyrillic_shapes() {
        // Letters that differ from every Latin letter must not collapse onto one another.
        let mut seen: [[u8; 8]; 128] = [[0; 8]; 128];
        let mut n = 0;
        for c in (0x410..=0x44Fu16).chain([0x401, 0x451]) {
            if latin_twin(c).is_some() {
                continue;
            }
            let gl = glyph(c);
            assert!(!seen[..n].contains(&gl), "{c:#x} duplicates another glyph");
            seen[n] = gl;
            n += 1;
        }
    }
}
