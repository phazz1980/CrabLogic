//! Prepares the module blobs for the WAMR prototype sketch.
//!
//! Run from `wamr-c3/`: `cargo run --manifest-path tools/prep/Cargo.toml`.
//! Writes `modules/*.wasm` (from the prototype `.wat`), `modules/*.aot` (wamrc, two
//! variants) and `sketch/modules.h`.
use std::{fmt::Write as _, fs, path::Path, process::Command};

const WAMRC: &str = ".deps/wamrc/wamrc.exe";
/// ESP32-C3 is RV32IMC, soft float, no atomics.
const TARGET: &[&str] = &[
    "--target=riscv32",
    "--target-abi=ilp32",
    "--cpu=generic-rv32",
    "--cpu-features=+m,+c,-a,-f,-d",
    "--xip",
    "--disable-simd",
    "--disable-ref-types",
];
/// (suffix, extra wamrc flags)
const VARIANTS: &[(&str, &[&str])] = &[("aot", &["--bounds-checks=1"]), ("aotnb", &["--bounds-checks=0"])];
/// Modules built from `wat/`: host call micro benchmarks and the wrapped-call variants of the
/// self tests (`tools/wrap_calls.py`).
const FROM_WAT: &[&str] = &["calls7", "calls1", "loop100", "selftest42w", "selftest42wi", "selftest107w", "selftest107wi"];
/// The first five are the sheet modules the "together" and swap tests use.
const MODULES: &[&str] = &[
    "blink", "counter", "thermostat17", "selftest42", "selftest107", "calls7", "calls1", "loop100", "selftest42w",
    "selftest42wi", "selftest107w", "selftest107wi",
];

fn main() {
    // `prep print <file.wasm>`: dump a module as text (debugging aid).
    let args: Vec<String> = std::env::args().collect();
    if args.len() == 3 && args[1] == "print" {
        println!("{}", wasmprinter::print_bytes(fs::read(&args[2]).unwrap()).unwrap());
        return;
    }
    for name in ["blink", "counter", "hang"] {
        let text = fs::read_to_string(format!("../{name}.wat")).unwrap();
        fs::write(format!("modules/{name}.wasm"), wat::parse_str(&text).unwrap()).unwrap();
    }
    for name in FROM_WAT {
        let text = fs::read_to_string(format!("wat/{name}.wat")).unwrap();
        fs::write(format!("modules/{name}.wasm"), wat::parse_str(&text).unwrap()).unwrap();
    }
    let mut h = String::from(
        "// Generated by tools/prep. Module blobs for the WAMR prototype.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n",
    );
    let mut table = String::from("struct Blob { const char *name; uint32_t mem; const uint8_t *wasm; size_t wasm_len; const uint8_t *aot; size_t aot_len; const uint8_t *aotnb; size_t aotnb_len; };\nstatic const Blob BLOBS[] = {\n");
    for m in MODULES {
        let wasm = format!("modules/{m}.wasm");
        let wasm_bytes = fs::read(&wasm).unwrap();
        let mut row = format!("  {{\"{m}\", {}, {m}_wasm, sizeof({m}_wasm)", crab_mem(&wasm_bytes));
        emit(&mut h, &format!("{m}_wasm"), &wasm_bytes);
        for (suffix, extra) in VARIANTS {
            let out = format!("modules/{m}.{suffix}");
            let st = Command::new(WAMRC)
                .args(TARGET)
                .args(*extra)
                .arg("-o")
                .arg(&out)
                .arg(&wasm)
                .output()
                .unwrap();
            if !st.status.success() || !Path::new(&out).exists() {
                println!("{m} {suffix}: wamrc failed\n{}{}", String::from_utf8_lossy(&st.stdout), String::from_utf8_lossy(&st.stderr));
                write!(row, ", nullptr, 0").unwrap();
                continue;
            }
            let bytes = fs::read(&out).unwrap();
            println!("{m:<14} wasm {:>6}  {suffix:<6} {:>6}", fs::metadata(&wasm).unwrap().len(), bytes.len());
            emit(&mut h, &format!("{m}_{suffix}"), &bytes);
            write!(row, ", {m}_{suffix}, sizeof({m}_{suffix})").unwrap();
        }
        table.push_str(&row);
        table.push_str("},\n");
    }
    let hang = fs::read("modules/hang.wasm").unwrap();
    emit(&mut h, "hang_wasm", &hang);
    table.push_str("};\n");
    h.push_str(&table);
    fs::write("sketch/modules.h", h).unwrap();
}

/// A 16-byte aligned array in flash (.rodata): the AOT loader executes its text in place.
fn emit(h: &mut String, name: &str, bytes: &[u8]) {
    writeln!(h, "alignas(16) static const uint8_t {name}[{}] = {{", bytes.len()).unwrap();
    for chunk in bytes.chunks(24) {
        h.push_str("  ");
        for b in chunk {
            write!(h, "{b},").unwrap();
        }
        h.push('\n');
    }
    h.push_str("};\n");
}

/// Value of the `crab.mem` custom section (u32 LE), 0 if absent.
fn crab_mem(wasm: &[u8]) -> u32 {
    fn leb(b: &[u8], p: &mut usize) -> usize {
        let (mut v, mut shift) = (0usize, 0);
        loop {
            let x = b[*p];
            *p += 1;
            v |= ((x & 0x7f) as usize) << shift;
            if x & 0x80 == 0 {
                return v;
            }
            shift += 7;
        }
    }
    let mut p = 8;
    while p < wasm.len() {
        let id = wasm[p];
        p += 1;
        let size = leb(wasm, &mut p);
        let end = p + size;
        if id == 0 {
            let mut q = p;
            let n = leb(wasm, &mut q);
            if &wasm[q..q + n] == b"crab.mem" {
                q += n;
                return u32::from_le_bytes(wasm[q..q + 4].try_into().unwrap());
            }
        }
        p = end;
    }
    0
}
